package manifest

import (
	"fmt"
	"strings"

	"github.com/tailscale/hujson"
)

// Манифест — это JSON с послаблениями: комментарии «//» и «/* */» и
// висячие запятые. Человек правит его руками, и комментарий рядом с
// ключом полезнее отдельного документа, до которого ещё надо дойти.
//
// Снимает послабления hujson. Своей реализации здесь больше нет: она
// делала ровно то же самое и проверялась ровно теми же случаями, но
// стоила полтораста строк разбора чужого формата — а разбор формата это
// именно то, что нужно брать готовым.
//
// Комментарии «#» поддерживались, пока keel читал манифест через JSON::PP
// с его режимом relaxed. Ни один разборщик JWCC их не берёт, а ради
// одного знака держать свой препроцессор — плохая сделка.

// Standardize превращает манифест в обычный JSON.
//
// Длина текста и нумерация строк при этом сохраняются: комментарии
// заменяются пробелами. Благодаря этому позиция ошибки, о которой скажет
// encoding/json, указывает на настоящую строку манифеста, а не на строку
// в обрезанном тексте.
func Standardize(raw []byte) ([]byte, error) {
	out, err := hujson.Standardize(raw)
	if err != nil {
		return nil, withHashHint(raw, err)
	}
	return out, nil
}

// withHashHint подсказывает про «#», если похоже, что дело в нём.
//
// Раньше такие комментарии работали, и у того, кто писал манифест по
// старой документации, они вполне могут быть. Сообщение «invalid
// character '#'» формально верное, но не говорит, что делать.
func withHashHint(raw []byte, err error) error {
	if !strings.Contains(err.Error(), "'#'") {
		return err
	}
	return fmt.Errorf("%w\n"+
		"Комментарии «#» больше не поддерживаются — замени их на «//».\n"+
		"Так было, пока манифест читался через JSON::PP; теперь формат — JSON с комментариями (JWCC)", err)
}
